import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const backendRoot = resolve(__dirname, '..');
const repoRoot = resolve(backendRoot, '..');
const sourceRoots = [resolve(backendRoot, 'src/cljs/knoxx/backend')];
const allowlistPath = resolve(backendRoot, 'config/error-boundary-allowlist.json');

const mode = process.argv[2] || '--check';

function usage() {
  console.error(`Usage: node backend/scripts/check-error-boundaries.mjs [--check|--inventory|--markdown|--write-baseline]\n\n--check           fail on non-allowlisted silent catch sites\n--inventory       print JSON inventory\n--markdown        print Markdown inventory\n--write-baseline  replace config/error-boundary-allowlist.json with current inventory`);
}

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) {
      files.push(...await walk(full));
    } else if (entry.isFile() && entry.name.endsWith('.cljs')) {
      files.push(full);
    }
  }
  return files;
}

function hash(text) {
  return createHash('sha1').update(text).digest('hex').slice(0, 12);
}

function siteId(file, line) {
  return `${file}#${hash(line.trim())}`;
}

function classify(line) {
  const trimmed = line.trim();
  if (/\(catch\s+[^\s)]+\s+_\b/.test(trimmed)) return 'ignored-catch-binding';
  if (/\.catch\s*\(fn\s*\[\s*_\s*\]/.test(trimmed)) return 'ignored-promise-catch-binding';
  return null;
}

function allowedInline(lines, idx) {
  const window = [lines[idx - 1], lines[idx], lines[idx + 1]].filter(Boolean).join('\n');
  return window.includes('knoxx-lint/allow-silent-catch');
}

async function inventory() {
  const files = (await Promise.all(sourceRoots.map(walk))).flat();
  const rows = [];
  for (const filePath of files) {
    const rel = relative(repoRoot, filePath);
    const lines = (await readFile(filePath, 'utf8')).split(/\r?\n/);
    lines.forEach((line, idx) => {
      const kind = classify(line);
      if (!kind || allowedInline(lines, idx)) return;
      rows.push({
        id: siteId(rel, line),
        file: rel,
        line: idx + 1,
        kind,
        snippet: line.trim(),
      });
    });
  }
  rows.sort((a, b) => a.file.localeCompare(b.file) || a.line - b.line);
  return rows;
}

async function loadAllowlist() {
  try {
    const parsed = JSON.parse(await readFile(allowlistPath, 'utf8'));
    return new Set((parsed.allowedSilentCatchSites || []).map((entry) => typeof entry === 'string' ? entry : entry.id).filter(Boolean));
  } catch (err) {
    if (err.code === 'ENOENT') return new Set();
    throw err;
  }
}

function markdown(rows) {
  const lines = [
    '# Knoxx Error Boundary Silent Catch Inventory',
    '',
    'Generated by `node backend/scripts/check-error-boundaries.mjs --markdown`.',
    '',
    '| file | line | kind | id | snippet |',
    '| --- | ---: | --- | --- | --- |',
  ];
  for (const row of rows) {
    lines.push(`| ${row.file} | ${row.line} | ${row.kind} | ${row.id} | \`${row.snippet.replaceAll('`', '\\`')}\` |`);
  }
  return `${lines.join('\n')}\n`;
}

async function writeBaseline(rows) {
  const unique = [...new Map(rows.map((row) => [row.id, row])).values()];
  const payload = {
    description: 'Baseline of pre-existing silent catch sites. New sites fail backend:error-boundaries unless explicitly documented with knoxx-lint/allow-silent-catch or added here during debt migration.',
    allowedSilentCatchSites: unique.map(({ id, file, kind, snippet }) => ({ id, file, kind, snippet })),
  };
  await writeFile(allowlistPath, `${JSON.stringify(payload, null, 2)}\n`);
  console.log(`[knoxx] wrote ${unique.length} silent catch baseline entries to ${relative(repoRoot, allowlistPath)} (${rows.length} observed sites)`);
}

async function check(rows) {
  const allowlist = await loadAllowlist();
  const violations = rows.filter((row) => !allowlist.has(row.id));
  if (violations.length > 0) {
    console.error('[knoxx] error-boundary lint failed. Silent catch sites must log, return data, rethrow, or be explicitly allowlisted:');
    for (const row of violations) {
      console.error(`  - ${row.file}:${row.line} ${row.kind} ${row.id}`);
      console.error(`    ${row.snippet}`);
    }
    console.error('\nPreferred fix: replace the catch with knoxx.backend.domain.error-observatory/log-error! or return an explicit {:ok false ...} result at the boundary.');
    process.exit(1);
  }
  console.log(`[knoxx] error-boundary check passed (${rows.length} baseline silent catch sites, ${allowlist.size} allowlisted).`);
}

if (!['--check', '--inventory', '--markdown', '--write-baseline'].includes(mode)) {
  usage();
  process.exit(2);
}

const rows = await inventory();
if (mode === '--inventory') {
  console.log(JSON.stringify(rows, null, 2));
} else if (mode === '--markdown') {
  process.stdout.write(markdown(rows));
} else if (mode === '--write-baseline') {
  await writeBaseline(rows);
} else {
  await check(rows);
}
